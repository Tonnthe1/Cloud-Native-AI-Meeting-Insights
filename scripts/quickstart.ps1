function Set-PublishedImages {
    $env:API_IMAGE = "$ImagePrefix/meeting-insights-api`:$Version"
    $env:WORKER_IMAGE = "$ImagePrefix/meeting-insights-worker`:$Version"
    $env:FRONTEND_IMAGE = "$ImagePrefix/meeting-insights-frontend`:$Version"
}

function Clear-PublishedImages {
    Remove-Item Env:API_IMAGE -ErrorAction SilentlyContinue
    Remove-Item Env:WORKER_IMAGE -ErrorAction SilentlyContinue
    Remove-Item Env:FRONTEND_IMAGE -ErrorAction SilentlyContinue
}

function Get-ContainerHealth([string]$Service) {
    Push-Location $RootDir
    try {
        $containerId = (& docker compose ps -q $Service).Trim()
    }
    finally {
        Pop-Location
    }
    if (-not $containerId) { return "missing" }
    return (& docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' $containerId).Trim()
}

function Wait-Service([string]$Service, [int]$TimeoutSeconds) {
    $started = Get-Date
    while ($true) {
        $health = Get-ContainerHealth $Service
        if ($health -in @("healthy", "running")) {
            Write-Log "$Service is $health."
            return
        }
        if ($health -in @("unhealthy", "exited", "dead")) {
            Invoke-Compose logs --tail=120 $Service
            throw "$Service entered state: $health"
        }
        if (((Get-Date) - $started).TotalSeconds -ge $TimeoutSeconds) {
            Invoke-Compose ps
            Invoke-Compose logs --tail=120 $Service
            throw "Timed out waiting for $Service; last state: $health"
        }
        Start-Sleep -Seconds 5
    }
}

function Start-Stack {
    if ($UsePrebuilt) {
        Set-PublishedImages
        Write-Log "Pulling published images ($Version)."
        Push-Location $RootDir
        try {
            & docker compose pull backend-api backend-worker frontend
            $pullSucceeded = $LASTEXITCODE -eq 0
        }
        finally {
            Pop-Location
        }
        if ($pullSucceeded) {
            Invoke-Compose up --detach --no-build --remove-orphans
            return
        }
        Write-Log "Published images were unavailable; falling back to a source build."
        Clear-PublishedImages
    }

    Write-Log "Building images from the checked-out source."
    Invoke-Compose up --detach --build --remove-orphans
}

function Show-Access {
    $bindLine = Get-Content $EnvFile | Where-Object { $_ -match '^BIND_ADDRESS=' } | Select-Object -Last 1
    $bindAddress = if ($bindLine) { $bindLine.Split('=', 2)[1] } else { "127.0.0.1" }
    if ($bindAddress -eq "0.0.0.0") { $bindAddress = "localhost" }

    Write-Host ""
    Write-Host "Meeting Insights is ready."
    Write-Host ""
    Write-Host "  App:           http://$bindAddress`:3000"
    Write-Host "  API docs:      http://$bindAddress`:8000/docs"
    Write-Host "  Worker health: http://$bindAddress`:8001/ready"
    Write-Host "  MinIO console: http://$bindAddress`:9001"
    Write-Host ""
    Write-Host "The first transcription can be slower while the Whisper model warms up."
}

if ($env:MEETING_INSIGHTS_ENV_ONLY -in @("true", "1")) {
    Ensure-Env
    Write-Log "Environment generation completed without starting Docker."
    return
}

Test-Docker
Ensure-Env

switch ($Command) {
    { $_ -in @("up", "start") } {
        Invoke-Compose config --quiet
        Start-Stack
        Wait-Service "backend-api" 300
        Wait-Service "frontend" 300
        Wait-Service "backend-worker" $WaitTimeoutSeconds
        Show-Access
    }
    "status" { Invoke-Compose ps }
    "logs" { Invoke-Compose logs --follow --tail=200 }
    { $_ -in @("down", "stop") } { Invoke-Compose down }
    "reset" {
        if ($env:CONFIRM_RESET -ne "yes") {
            throw "Reset deletes all local data. Set CONFIRM_RESET=yes and run again."
        }
        Invoke-Compose down --volumes --remove-orphans
        Write-Log "All local containers and volumes were removed."
    }
    { $_ -in @("doctor", "check") } {
        if ($UsePrebuilt) { Set-PublishedImages }
        Invoke-Compose config --quiet
        Write-Log "Docker, Compose, environment configuration, and service topology look valid."
    }
}
