param(
    [ValidateSet("up", "start", "status", "logs", "down", "stop", "reset", "doctor", "check")]
    [string]$Command = "up"
)

$ErrorActionPreference = "Stop"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$RootDir = Split-Path -Parent $ScriptDir
$EnvFile = Join-Path $RootDir ".env"
$WaitTimeoutSeconds = if ($env:WAIT_TIMEOUT_SECONDS) { [int]$env:WAIT_TIMEOUT_SECONDS } else { 1200 }
$UsePrebuilt = $env:MEETING_INSIGHTS_PREBUILT -in @("true", "1")
$Version = if ($env:MEETING_INSIGHTS_VERSION) { $env:MEETING_INSIGHTS_VERSION } else { "latest" }
$ImagePrefix = if ($env:MEETING_INSIGHTS_IMAGE_PREFIX) { $env:MEETING_INSIGHTS_IMAGE_PREFIX } else { "ghcr.io/tonnthe1" }

function Write-Log([string]$Message) {
    Write-Host "[meeting-insights] $Message"
}

function Invoke-Compose {
    param([Parameter(ValueFromRemainingArguments = $true)][string[]]$ComposeArgs)
    Push-Location $RootDir
    try {
        & docker compose @ComposeArgs
        if ($LASTEXITCODE -ne 0) {
            throw "docker compose failed with exit code $LASTEXITCODE"
        }
    }
    finally {
        Pop-Location
    }
}

function Test-Docker {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw "Docker Desktop is required: https://docs.docker.com/desktop/"
    }
    & docker info *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker is installed but Docker Desktop is not running."
    }
    & docker compose version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose v2 is required."
    }
}

function New-Secret {
    $bytes = New-Object byte[] 24
    $generator = [Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    }
    finally {
        $generator.Dispose()
    }
    return -join ($bytes | ForEach-Object { $_.ToString("x2") })
}

